#!/usr/bin/env python3
"""Embed the ISRG root certificates as DER tables (src/ca_roots_gen.cpp) after checking their SHA-256 fingerprints."""
import argparse
import hashlib
import pathlib
import ssl

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROOTS = [
    ("ISRG_ROOT_X1", "ISRG Root X1", "/etc/ssl/certs/ISRG_Root_X1.pem",
     "96bcec06264976f37460779acf28c5a7cfe8a3c0aae11a8ffcee05c0bddf08c6"),
    ("ISRG_ROOT_X2", "ISRG Root X2", "/etc/ssl/certs/ISRG_Root_X2.pem",
     "69729b8e15a86efc177a57afb7171dfc64add28c2fca8cf1507e34453ccb1470"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "src" / "ca_roots_gen.cpp"))
    args = ap.parse_args()
    out = [
        "// Generated by tools/gen_ca_roots.py from the ISRG root certificates. Do not edit.",
        '#include "ca_roots.h"',
        "",
    ]
    entries = []
    for name, label, path, sha256 in ROOTS:
        der = ssl.PEM_cert_to_DER_cert(pathlib.Path(path).read_text("ascii"))
        got = hashlib.sha256(der).hexdigest()
        if got != sha256:
            raise SystemExit(f"{label}: SHA-256 {got} does not match pinned {sha256}")
        out.append(f"// {label}, SHA-256 {sha256}")
        out.append(f"static const uint8_t {name}[] PROGMEM = {{")
        out += ["  " + ",".join(f"0x{b:02X}" for b in der[i:i + 20]) + "," for i in range(0, len(der), 20)]
        out += ["};", ""]
        entries.append(f'  {{"{label}", {name}, sizeof({name})}},')
        print(f"{label}: {len(der)} bytes")
    out.append("const CaRoot CA_ROOTS[] = {")
    out += entries
    out += ["};", "const size_t CA_ROOT_COUNT = sizeof(CA_ROOTS) / sizeof(CA_ROOTS[0]);", ""]
    pathlib.Path(args.out).write_text("\n".join(out), "utf-8")


if __name__ == "__main__":
    main()
