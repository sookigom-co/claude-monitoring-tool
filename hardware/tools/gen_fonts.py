#!/usr/bin/env python3
"""Render the glyph subsets used by the firmware into 4-bit anti-aliased C tables (src/fonts_gen.cpp)."""
import argparse
import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
REGULAR = "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"
BOLD = "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"
ASCII = "".join(chr(c) for c in range(32, 127))
DIGITS = "0123456789"


def load_face(path, size):
    for index in range(10):
        face = ImageFont.truetype(path, size, index=index)
        if face.getname()[0] == "Noto Sans CJK KR":
            return face
    raise SystemExit(f"Noto Sans CJK KR face not found in {path}")


def render(face, chars):
    glyphs = []
    for ch in sorted(set(chars)):
        adv = round(face.getlength(ch))
        x0, y0, x1, y1 = face.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        data = b""
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=face, fill=255, anchor="ls")
            px = [v >> 4 for v in img.tobytes()]
            if len(px) % 2:
                px.append(0)
            data = bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
        glyphs.append(dict(code=ord(ch), w=w, h=h, xo=x0, yo=y0, adv=adv, data=data))
    digit_adv = max((g["adv"] for g in glyphs if chr(g["code"]) in DIGITS), default=0)
    for g in glyphs:
        if chr(g["code"]) in DIGITS:
            g["xo"] += (digit_adv - g["adv"]) // 2
            g["adv"] = digit_adv
    return glyphs


def emit(name, glyphs):
    ascent = max(-g["yo"] for g in glyphs if g["h"])
    descent = max(max(g["yo"] + g["h"] for g in glyphs if g["h"]), 0)
    blob, rows, offset = bytearray(), [], 0
    for g in glyphs:
        rows.append(f'  {{0x{g["code"]:04X}, {offset}, {g["w"]}, {g["h"]}, {g["xo"]}, {g["yo"]}, {g["adv"]}}},')
        blob += g["data"]
        offset += len(g["data"])
    lines = [",".join(f"0x{b:02X}" for b in blob[i:i + 20]) + "," for i in range(0, len(blob), 20)]
    out = [f"static const uint8_t {name}_bitmap[] PROGMEM = {{"]
    out += ["  " + ln for ln in lines]
    out += ["};", f"static const Glyph {name}_glyphs[] PROGMEM = {{"]
    out += rows
    out += ["};", f"const Font {name} = {{{name}_glyphs, {len(glyphs)}, {name}_bitmap, {ascent}, {descent}}};", ""]
    return "\n".join(out), len(blob)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "src" / "fonts_gen.cpp"))
    args = ap.parse_args()
    korean = "".join(ch for ch in (ROOT / "tools" / "glyphs_ko.txt").read_text("utf-8") if ord(ch) > 127)
    specs = [
        ("FONT_L", BOLD, 56, DIGITS + ":-"),
        ("FONT_M", BOLD, 22, ASCII + korean),
        ("FONT_S", REGULAR, 16, ASCII + korean),
        ("FONT_XS", REGULAR, 13, ASCII + korean),
        ("FONT_P", BOLD, 22, DIGITS + "%-"),
        ("FONT_PS", BOLD, 16, DIGITS + "%-"),
    ]
    parts = [
        "// Generated by tools/gen_fonts.py from Noto Sans CJK KR (SIL Open Font License 1.1). Do not edit.",
        '#include "fonts.h"',
        "",
    ]
    for name, path, size, chars in specs:
        text, nbytes = emit(name, render(load_face(path, size), chars))
        parts.append(text)
        print(f"{name}: {len(set(chars))} glyphs, {nbytes} bytes")
    pathlib.Path(args.out).write_text("\n".join(parts), "utf-8")


if __name__ == "__main__":
    main()
